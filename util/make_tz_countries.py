#!/usr/bin/env python3
"""
make_tz_countries.py — generate docs/assets/js/tz-country.js, the IANA
timezone → ISO 3166-1 country table the News and Calendar pages use to
suggest a country filter (docs/assets/js/country-suggest.js).

The browser reports its timezone without a network request or a permission
prompt (Intl.DateTimeFormat().resolvedOptions().timeZone), and nearly every
zone belongs to one country, so this is the privacy-respecting way to guess
where a reader is. The alternative, an IP-geolocation service, would send
every visitor's address to a third party.

Source is tzdata's zone.tab (one country per zone; zone1970.tab merges
countries that share a zone, which is no use here), plus LEGACY_ALIASES:
some browsers still report pre-2000s names such as Asia/Calcutta, which
zone.tab doesn't list. Run once and commit the output; the build never
reads zone.tab. Re-run only when tzdata adds zones worth knowing about.

    python util/make_tz_countries.py                          # /usr/share/zoneinfo/zone.tab
    python util/make_tz_countries.py --zonetab path/zone.tab
"""

