def read_zone_tab(path):
    table = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            parts = line.rstrip("\n").split("\t")
            table[parts[2]] = parts[0]
    return table


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--zonetab", default="/usr/share/zoneinfo/zone.tab")
    args = ap.parse_args()
    table = read_zone_tab(args.zonetab)
    for zone, cc in LEGACY_ALIASES.items():
        table.setdefault(zone, cc)
    body = json.dumps(dict(sorted(table.items())), separators=(",", ":"))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by util/make_tz_countries.py from tzdata's zone.tab; don't edit by hand.\n")
        f.write("// IANA timezone -> ISO 3166-1 alpha-2, for docs/assets/js/country-suggest.js.\n")
        f.write(f"window.DOD_TZ_COUNTRY = {body};\n")
    print(f"Wrote {len(table)} zones to {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
